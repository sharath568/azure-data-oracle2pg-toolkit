"""Suggested PostgreSQL DDL from an Oracle inventory (``o2pg map-types``).

The output is a starting point for review, not something to run blindly. It
covers schemas, sequences, tables, keys, partitioning clauses and foreign keys.
Anything that needs a human decision is left as a ``TODO`` comment.
"""

from __future__ import annotations

import re
from collections import defaultdict

from o2pg import __version__
from o2pg.inventory import Column, Constraint, Inventory, Sequence, Table
from o2pg.rules.objects import BIGINT_MAX, POSTGRES_RESERVED_WORDS
from o2pg.typemap import is_user_defined, map_column

_SIMPLE = re.compile(r"^[a-z_][a-z0-9_$]*$")
_NUMBER_LITERAL = re.compile(r"^-?\d+(\.\d+)?$")
_STRING_LITERAL = re.compile(r"^'(?:[^']|'')*'$")
_NEXTVAL = re.compile(
    r'^(?:"?([\w$#]+)"?\s*\.\s*)?"?([\w$#]+)"?\s*\.\s*"?NEXTVAL"?$', re.IGNORECASE
)
_QUOTED_UPPER = re.compile(r'"([A-Z][A-Z0-9_$#]*)"')
_DEFAULT_FUNCTIONS = {
    "SYSDATE": "LOCALTIMESTAMP(0)",
    "SYSTIMESTAMP": "CURRENT_TIMESTAMP",
    "SYS_GUID()": "gen_random_uuid()",
    "USER": "CURRENT_USER",
    "CURRENT_DATE": "CURRENT_DATE",
}


def ident(name: str) -> str:
    """Lower-case an Oracle identifier and quote it only if PostgreSQL requires it."""
    lowered = name.lower()
    if _SIMPLE.match(lowered) and name.upper() not in POSTGRES_RESERVED_WORDS:
        return lowered
    return '"' + lowered.replace('"', '""') + '"'


def qualified(owner: str, name: str) -> str:
    """``schema.name`` with both parts converted by :func:`ident`."""
    return f"{ident(owner)}.{ident(name)}"


def unquote_identifiers(expression: str) -> str:
    """Turn Oracle's quoted upper-case identifiers in an expression into PostgreSQL names."""
    return _QUOTED_UPPER.sub(lambda m: ident(m.group(1)), expression)


def translate_default(expression: str) -> tuple[str | None, str]:
    """Translate a simple Oracle column default.

    Returns ``(sql, note)``: ``sql`` is None when the default needs a human.
    """
    expr = expression.strip()
    if not expr or expr.upper() == "NULL":
        return None, ""
    if _NUMBER_LITERAL.match(expr) or _STRING_LITERAL.match(expr):
        return expr, ""
    if expr.upper() in _DEFAULT_FUNCTIONS:
        return _DEFAULT_FUNCTIONS[expr.upper()], f"was {expr}"
    nextval = _NEXTVAL.match(expr)
    if nextval:
        owner, seq = nextval.groups()
        target = qualified(owner, seq) if owner else ident(seq)
        return f"nextval('{target}')", f"was {expr}"
    return None, f"TODO default: {expr}"


def _column_line(column: Column, inventory: Inventory) -> tuple[str, str]:
    """Return the SQL for one column definition and an optional trailing note."""
    notes: list[str] = []
    if is_user_defined(column, inventory.user_type_names):
        pg_type = "jsonb"
        notes.append(f"TODO user-defined type {column.data_type}: normalise or keep as jsonb")
    else:
        mapping = map_column(column)
        pg_type = mapping.pg_type or "text"
        if mapping.pg_type is None:
            notes.append(f"TODO no mapping for {column.data_type}")
        elif mapping.note and not mapping.exact:
            notes.append(mapping.note)
    sql = f"{ident(column.name)} {pg_type}"
    if column.identity:
        sql += " GENERATED BY DEFAULT AS IDENTITY"
    elif column.virtual:
        sql += f" GENERATED ALWAYS AS ({unquote_identifiers(column.data_default.strip())}) STORED"
        notes.append("review generated expression")
    elif column.data_default:
        default, note = translate_default(column.data_default)
        if default:
            sql += f" DEFAULT {default}"
        if note:
            notes.append(note)
    if not column.nullable:
        sql += " NOT NULL"
    return sql, "; ".join(notes)


def _key_line(constraint: Constraint) -> str:
    kind = "PRIMARY KEY" if constraint.type.upper() == "P" else "UNIQUE"
    cols = ", ".join(ident(c) for c in constraint.columns)
    return f"CONSTRAINT {ident(constraint.name)} {kind} ({cols})"


def _table_ddl(table: Table, inventory: Inventory) -> list[str]:
    key = (table.owner, table.name)
    entries: list[tuple[str, str]] = [
        _column_line(c, inventory) for c in inventory.columns_by_table.get(key, [])
    ]
    checks: list[str] = []
    for con in inventory.constraints_by_table.get(key, []):
        kind = con.type.upper()
        if kind in {"P", "U"} and con.columns:
            entries.append((_key_line(con), ""))
        elif (
            kind == "C"
            and con.search_condition
            and "IS NOT NULL" not in con.search_condition.upper()
        ):
            checks.append(f"-- TODO check constraint {con.name}: CHECK ({con.search_condition})")
    head = f"CREATE TABLE {qualified(table.owner, table.name)} ("
    if table.temporary:
        head = (
            "-- Oracle global temporary table: create it per session in PostgreSQL\n"
            f"-- CREATE TEMP TABLE {ident(table.name)} ("
        )
    lines = [head]
    for i, (sql, note) in enumerate(entries):
        comma = "," if i < len(entries) - 1 else ""
        comment = f"  -- {note}" if note else ""
        lines.append(f"    {sql}{comma}{comment}")
    part = inventory.partitioning.get(key)
    tail = ")"
    if part:
        kind = part.partitioning_type.upper()
        keys = ", ".join(ident(k) for k in part.partition_keys)
        if kind in {"RANGE", "LIST", "HASH"}:
            tail = f") PARTITION BY {kind} ({keys})"
        else:
            checks.append(f"-- TODO {kind} partitioning has no PostgreSQL equivalent")
    lines.append(tail + ";")
    if part and part.partition_keys:
        keys_upper = {k.upper() for k in part.partition_keys}
        key_list = ", ".join(part.partition_keys)
        for con in inventory.constraints_by_table.get(key, []):
            columns = {c.upper() for c in con.columns}
            if con.type.upper() in {"P", "U"} and not keys_upper <= columns:
                checks.append(f"-- TODO {con.name} must include the partition key ({key_list})")
    if table.temporary:
        lines = [lines[0]] + [f"-- {line}" for line in lines[1:]]
    return lines + checks


def _sequence_ddl(seq: Sequence) -> str:
    parts = [f"CREATE SEQUENCE {qualified(seq.owner, seq.name)}"]
    if seq.increment_by not in (None, 1):
        parts.append(f"INCREMENT BY {seq.increment_by}")
    if seq.max_value is not None and seq.max_value <= BIGINT_MAX:
        parts.append(f"MAXVALUE {seq.max_value}")
    if seq.last_number is not None:
        parts.append(f"START WITH {seq.last_number}")
    if seq.cycle:
        parts.append("CYCLE")
    return " ".join(parts) + ";"


def suggest_ddl(inventory: Inventory) -> str:
    """Return suggested PostgreSQL DDL for every table and sequence in the inventory."""
    out = [
        f"-- Suggested PostgreSQL DDL generated by o2pg {__version__}",
        "-- Review before running: types are conservative and TODO comments need decisions.",
        "",
    ]
    schemas = sorted({t.owner for t in inventory.tables} | {s.owner for s in inventory.sequences})
    out += [f"CREATE SCHEMA IF NOT EXISTS {ident(s)};" for s in schemas]
    if inventory.sequences:
        out += [
            "",
            "-- Sequences (START WITH uses LAST_NUMBER at collection time; re-sync at cutover)",
        ]
        out += [_sequence_ddl(s) for s in inventory.sequences]
    for table in inventory.tables:
        out += ["", *_table_ddl(table, inventory)]
    by_name: dict[tuple[str, str], Constraint] = {
        (c.owner, c.name): c for c in inventory.constraints
    }
    foreign = [c for c in inventory.constraints if c.type.upper() == "R" and c.columns]
    if foreign:
        out += ["", "-- Foreign keys"]
    by_table: dict[tuple[str, str], list[str]] = defaultdict(list)
    for con in foreign:
        parent = by_name.get((con.r_owner or con.owner, con.r_constraint_name))
        if parent is None:
            by_table[(con.owner, con.table_name)].append(
                f"-- TODO {con.name}: referenced constraint {con.r_constraint_name} not in "
                f"inventory"
            )
            continue
        on_delete = ""
        if con.delete_rule.upper() in {"CASCADE", "SET NULL"}:
            on_delete = f" ON DELETE {con.delete_rule.upper()}"
        by_table[(con.owner, con.table_name)].append(
            f"ALTER TABLE {qualified(con.owner, con.table_name)} ADD CONSTRAINT {ident(con.name)} "
            f"FOREIGN KEY ({', '.join(ident(c) for c in con.columns)}) "
            f"REFERENCES {qualified(parent.owner, parent.table_name)} "
            f"({', '.join(ident(c) for c in parent.columns)}){on_delete};"
        )
    for key in sorted(by_table):
        out += by_table[key]
    return "\n".join(out) + "\n"
