"""Rule catalogue output: the ``o2pg rules`` command and ``docs/rules.md``."""

from __future__ import annotations

import json
from collections.abc import Iterable

from o2pg.rules import Category, Rule, all_rules


def rules_markdown(rules: Iterable[Rule] | None = None) -> str:
    """Markdown reference for every rule, grouped by category.

    ``docs/rules.md`` is generated from this function by ``scripts/gen_rules_doc.py``
    and a test fails if the two drift apart.
    """
    selected = list(all_rules() if rules is None else rules)
    lines = [
        "# o2pg rule reference",
        "",
        "<!-- Generated by scripts/gen_rules_doc.py from the rule registry. Do not edit by "
        "hand. -->",
        "",
        f"{len(selected)} rules. Effort is in effort points per affected object. "
        "Rules marked **AI risk** feed the AI readiness section of the report.",
        "",
        "| Category | Prefix | Rules |",
        "|---|---|---|",
    ]
    for category in Category:
        count = sum(1 for r in selected if r.category is category)
        lines.append(f"| {category.value} | {category.prefix} | {count} |")
    lines.append("")
    for category in Category:
        members = [r for r in selected if r.category is category]
        if not members:
            continue
        lines += [f"## {category.value}", ""]
        for r in members:
            flags = [f"severity **{r.severity.value}**", f"effort {r.effort:g}"]
            if r.ai_risk:
                flags.append("**AI risk**")
            if r.extensions:
                flags.append("extensions: " + ", ".join(f"`{e}`" for e in r.extensions))
            lines += [
                f"### {r.id}: {r.title}",
                "",
                " · ".join(flags),
                "",
                r.description,
                "",
                f"**Remediation:** {r.remediation}",
                "",
            ]
            if r.ai_risk:
                lines += [f"**Tell the model:** {r.ai_risk}", ""]
    return "\n".join(lines)


def rules_table(rules: Iterable[Rule] | None = None) -> str:
    """Plain-text table for the terminal."""
    selected = list(all_rules() if rules is None else rules)
    rows = [("ID", "SEVERITY", "CATEGORY", "AI", "TITLE")]
    rows += [
        (r.id, r.severity.value, r.category.value, "yes" if r.ai_risk else "", r.title)
        for r in selected
    ]
    widths = [max(len(row[i]) for row in rows) for i in range(4)]
    lines = [
        "  ".join(cell.ljust(widths[i]) for i, cell in enumerate(row[:4])) + "  " + row[4]
        for row in rows
    ]
    return "\n".join(lines) + f"\n\n{len(selected)} rules\n"


def rules_json(rules: Iterable[Rule] | None = None) -> str:
    """JSON array describing each rule."""
    selected = list(all_rules() if rules is None else rules)
    payload = [
        {
            "id": r.id,
            "title": r.title,
            "category": r.category.value,
            "severity": r.severity.value,
            "effort": r.effort,
            "description": r.description,
            "remediation": r.remediation,
            "ai_risk": r.ai_risk,
            "extensions": list(r.extensions),
        }
        for r in selected
    ]
    return json.dumps(payload, indent=2) + "\n"


__all__ = ["rules_json", "rules_markdown", "rules_table"]
