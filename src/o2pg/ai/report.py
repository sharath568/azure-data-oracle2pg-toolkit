"""The ai-convert report and the candidate files it points to."""

from __future__ import annotations

import json
from pathlib import Path

from o2pg import __version__
from o2pg.ai.gates import BEHAVIOUR
from o2pg.ai.pipeline import (
    COMPILES,
    ERROR,
    REJECTED,
    SKIPPED,
    STATIC_ONLY,
    STATUS_ORDER,
    UNRESOLVED,
    VERIFIED,
    AiRun,
    UnitOutcome,
    as_dict,
)
from o2pg.ai.providers import PRICES_CHECKED, unit_filename
from o2pg.ai.scope import SKIP_DESIGN

_MEANING = {
    VERIFIED: "passed the static, compile and behaviour gates",
    COMPILES: "passed static and compile; no equivalence cases, so behaviour is untested",
    STATIC_ONLY: "passed the static gate; run with --dsn to compile and test it",
    UNRESOLVED: "the model left review points it could not resolve",
    REJECTED: "failed a gate; the mechanical output stands",
    ERROR: "no usable answer from the provider",
    SKIPPED: "not sent to the model",
}


def candidate_filename(outcome: UnitOutcome) -> str:
    """``lab.highest_paid.sql`` for a unit."""
    return unit_filename(outcome.name)[: -len(".json")] + ".sql"


def candidate_sql(outcome: UnitOutcome) -> str:
    """A candidate file: a header saying what it is, the preamble, the answer."""
    assert outcome.answer is not None
    warning = {
        VERIFIED: "Matches Oracle on every equivalence case. Review it like any code change.",
        COMPILES: "Compiles, but no equivalence case covers it. Test it before using it.",
        STATIC_ONLY: "Not compiled or tested. Run ai-convert with --dsn first.",
        UNRESOLVED: "Incomplete: review markers are still in it. Do not deploy.",
        REJECTED: "REJECTED by the gates. Kept for review only. Do not deploy.",
    }.get(outcome.status, "")
    lines = [
        f"-- {outcome.name}: AI-assisted conversion by o2pg {__version__} ai-convert",
        f"-- Status: {outcome.status}. {warning}",
    ]
    if outcome.reason:
        lines.append(f"-- Reason: {outcome.reason}")
    if outcome.contract_change:
        why = outcome.answer.signature_reason or "required by a review point"
        lines.append(f"-- SIGNATURE CHANGED: {why}. Update every caller.")
    for change in outcome.answer.changes:
        lines.append(f"-- {change['rule']}: {change['change']}")
    for assumption in outcome.answer.assumptions:
        lines.append(f"-- Assumes: {assumption}")
    lines.append("")
    lines += outcome.preamble
    lines += ["", outcome.answer.sql.strip(), ""]
    return "\n".join(lines)


def write_outputs(run: AiRun, directory: Path) -> list[Path]:
    """Write candidate files, verified.sql, ai-report.md and ai-report.json."""
    directory.mkdir(parents=True, exist_ok=True)
    written = []
    verified_parts = []
    for outcome in run.outcomes:
        if outcome.answer is None or outcome.status in {SKIPPED, ERROR}:
            continue
        path = directory / candidate_filename(outcome)
        path.write_text(candidate_sql(outcome), encoding="utf-8")
        written.append(path)
        if outcome.status == VERIFIED:
            verified_parts.append(candidate_sql(outcome))
    if verified_parts:
        path = directory / "verified.sql"
        header = (
            f"-- Every unit that passed all three gates, from o2pg {__version__} ai-convert.\n"
            "-- Matching Oracle on the equivalence cases is evidence, not proof.\n"
            "-- Review each one.\n\n"
        )
        path.write_text(header + "\n".join(verified_parts), encoding="utf-8")
        written.append(path)
    md = directory / "ai-report.md"
    md.write_text(report_markdown(run), encoding="utf-8")
    js = directory / "ai-report.json"
    js.write_text(json.dumps(as_dict(run), indent=2) + "\n", encoding="utf-8")
    return [*written, md, js]


def _cell(text: str) -> str:
    return " ".join(text.replace("|", "\\|").split())


def report_markdown(run: AiRun) -> str:
    """The Markdown report."""
    sent = [o for o in run.outcomes if o.sent]
    cases = [c for o in run.outcomes for c in o.cases]
    usage = run.usage
    cost = run.cost
    out = [
        "# o2pg ai-convert report",
        "",
        f"Generated by o2pg {__version__} with {run.provider} ({run.model or 'unknown model'}), "
        f"prompt {run.prompt_version}, up to {run.max_attempts} attempt(s) per unit. "
        "The mechanical output is unchanged; candidates are in this directory.",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Units | {len(run.outcomes)} |",
        f"| Sent to the model | {len(sent)} |",
    ]
    for status in STATUS_ORDER:
        if status == SKIPPED:
            continue
        out.append(f"| {status.capitalize()} | {run.count(status)} |")
    design = sum(1 for o in run.outcomes if o.reason.startswith(SKIP_DESIGN))
    out.append(f"| Skipped: needs a design decision | {design} |")
    if cases:
        passed = sum(1 for c in cases if c.passed)
        out.append(f"| Equivalence cases matching Oracle | {passed} of {len(cases)} |")
    out.append(
        f"| Tokens (prompt + completion) | {usage.prompt_tokens} + {usage.completion_tokens} |"
    )
    if cost is not None:
        out.append(f"| Estimated cost | ${cost:.4f} (list prices checked {PRICES_CHECKED}) |")
    if not run.database:
        out += [
            "",
            "No database was given (--dsn), so only the static gate ran. "
            "Nothing here has been compiled or tested.",
        ]
    out += ["", "## Units", "", "| Unit | Review rules | Status | Attempts | Cases | Notes |"]
    out.append("|---|---|---|---|---|---|")
    for o in sorted(run.outcomes, key=lambda x: (STATUS_ORDER.index(x.status), x.name)):
        rules = ", ".join(r.replace("O2PG-", "") for r in o.rules) or "-"
        cases_text = f"{o.cases_passed}/{len(o.cases)}" if o.cases else "-"
        notes = o.reason
        if o.contract_change and o.status != REJECTED:
            notes = ("signature changed. " + notes).strip()
        out.append(
            f"| `{o.name}` | {rules} | {o.status} | {o.attempts or '-'} | {cases_text} "
            f"| {_cell(notes)} |"
        )
    rejected = [o for o in run.outcomes if o.status == REJECTED]
    if rejected:
        out += ["", "## What the gates caught", ""]
        for o in rejected:
            out.append(f"### `{o.name}`")
            out.append("")
            for gate in o.gates:
                if not gate.passed and gate.gate != BEHAVIOUR:
                    out.append(f"- {gate.gate} gate, attempt {gate.attempt}: {_cell(gate.detail)}")
            for case in o.cases:
                if not case.passed:
                    out.append(f"- case `{case.case.id}`: {_cell('; '.join(case.diffs))}")
            out.append("")
    recovered = [
        o for o in run.outcomes if o.status != REJECTED and any(not g.passed for g in o.gates)
    ]
    if recovered:
        out += ["", "## Fixed after feedback", ""]
        out.append(
            "The first answer failed a gate; the error went back to the model and a later "
            "answer passed."
        )
        out.append("")
        for o in recovered:
            for gate in o.gates:
                if not gate.passed:
                    where = f"`{o.name}`, {gate.gate} gate, attempt {gate.attempt}"
                    out.append(f"- {where}: {_cell(gate.detail)}")
    changed = [o for o in run.outcomes if o.contract_change and o.status != REJECTED]
    if changed:
        out += ["", "## Signature changes", ""]
        out.append("These routines no longer have the Oracle signature. Every caller must change.")
        out.append("")
        for o in changed:
            why = o.answer.signature_reason if o.answer else ""
            out.append(f"- `{o.name}`: {_cell(why) or 'required by a review point'}")
    skipped = [o for o in run.outcomes if o.reason.startswith(SKIP_DESIGN)]
    if skipped:
        out += ["", "## Needs a person", ""]
        out.append(
            "These units were not sent to the model. The fix is a design choice, not a rewrite."
        )
        out.append("")
        for o in skipped:
            out.append(f"- `{o.name}`: {o.reason[len(SKIP_DESIGN) + 2 :]}")
    out += [
        "",
        "## How to read this",
        "",
        *[f"- **{status}**: {_MEANING[status]}" for status in STATUS_ORDER],
        "",
        "Matching Oracle on the equivalence cases is evidence, not proof. The cases cover what "
        "someone thought to test. Add a case for every bug you find.",
        "",
    ]
    return "\n".join(out)
