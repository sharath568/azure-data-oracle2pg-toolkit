"""Conversion report (Markdown and JSON) and the conversion rule reference."""

from __future__ import annotations

import json
from collections import Counter
from typing import Any

from o2pg import __version__
from o2pg.convert.engine import (
    STATUS_BLOCKED,
    STATUS_CONVERTED,
    STATUS_NOT_CONVERTED,
    STATUS_REVIEW,
    ConversionResult,
    ConvertedObject,
)
from o2pg.convert.registry import ConversionRule, conversion_rules, get_conversion_rule

_STATUS_TEXT = {
    STATUS_CONVERTED: "converted",
    STATUS_REVIEW: "converted, needs review",
    STATUS_BLOCKED: "blocked",
    STATUS_NOT_CONVERTED: "not converted",
}


def _pct(clean: int, total: int) -> str:
    return f"{100.0 * clean / total:.1f}%" if total else "n/a"


def _unit_counts(result: ConversionResult) -> Counter[str]:
    return Counter(u.status for u in result.units if u.kind not in {"PACKAGE STATE"})


def report_markdown(result: ConversionResult) -> str:
    """Human-readable conversion report."""
    reviews = result.reviews
    blocking = sum(1 for r in reviews if r.blocking)
    counts = _unit_counts(result)
    lines = [
        "# o2pg conversion report",
        "",
        f"Generated by o2pg {__version__}. The converter makes mechanical rewrites only and "
        "leaves an `O2PG-REVIEW` marker wherever a person has to decide. It is not a parser and "
        "does not prove the result equivalent: test the converted code.",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Objects | {len(result.objects)} |",
        f"| Routines and triggers converted with no review points | {counts[STATUS_CONVERTED]} |",
        f"| Converted, non-blocking review points only | {counts[STATUS_REVIEW]} |",
        f"| Blocked (at least one blocking review point) | {counts[STATUS_BLOCKED]} |",
        f"| Not converted (kept as comments) | {counts[STATUS_NOT_CONVERTED]} |",
        f"| Rewrites applied | {sum(result.rewrites.values())} |",
        f"| Review points | {len(reviews)} ({blocking} blocking) |",
        f"| Mechanical coverage | {_pct(result.clean_statements, result.statements)} "
        f"({result.clean_statements} of {result.statements} statements need no review) |",
        "",
        "Mechanical coverage counts `;`-terminated statements (plus each routine header) and "
        "treats a statement as needing review when a review marker sits on or above its "
        "lines. Units marked converted or needs review should `CREATE` in PostgreSQL; blocked "
        "units contain Oracle code that will not work until someone rewrites it.",
        "",
        "## Objects",
        "",
        "| Object | Type | File | Status | Rewrites | Review points | Coverage |",
        "|---|---|---|---|---|---|---|",
    ]
    for obj in result.objects:
        obj_reviews = obj.reviews
        lines.append(
            f"| {obj.qualified} | {' + '.join(obj.source_types)} | `{obj.filename}` | "
            f"{_STATUS_TEXT[obj.status]} | {sum(obj.all_rewrites.values())} | "
            f"{len(obj_reviews)} ({sum(1 for r in obj_reviews if r.blocking)} blocking) | "
            f"{_pct(obj.clean_statements, obj.statements)} |"
        )
    lines += ["", "## Rewrites applied", ""]
    rewrites = result.rewrites
    if rewrites:
        lines += ["| Rule | Rewrite | Count | Note |", "|---|---|---|---|"]
        for rule_id, count in sorted(rewrites.items()):
            rule = get_conversion_rule(rule_id)
            lines.append(f"| {rule.id} | {rule.title} | {count} | {rule.note} |")
    else:
        lines.append("None.")
    lines += ["", "## Review points by rule", ""]
    by_rule = Counter(r.rule for r in reviews)
    if by_rule:
        lines += ["| Rule | Review point | Blocking | Count |", "|---|---|---|---|"]
        for rule_id, count in sorted(by_rule.items()):
            rule = get_conversion_rule(rule_id)
            lines.append(
                f"| {rule.id} | {rule.title} | {'yes' if rule.blocking else 'no'} | {count} |"
            )
    else:
        lines.append("None.")
    lines += ["", "## Details", ""]
    for obj in result.objects:
        lines += _object_section(obj)
    return "\n".join(lines).rstrip("\n") + "\n"


def _object_section(obj: ConvertedObject) -> list[str]:
    lines = [
        f"### {obj.qualified} ({' + '.join(obj.source_types)})",
        "",
        f"File `{obj.filename}`. Status: {_STATUS_TEXT[obj.status]}. Coverage "
        f"{_pct(obj.clean_statements, obj.statements)} ({obj.clean_statements} of "
        f"{obj.statements} statements).",
        "",
        "| Unit | Kind | Status | Statements | Need review |",
        "|---|---|---|---|---|",
    ]
    for unit in obj.units:
        lines.append(
            f"| {unit.name} | {unit.kind.lower()} | {_STATUS_TEXT[unit.status]} | "
            f"{unit.statements} | {unit.statements - unit.clean_statements} |"
        )
    lines.append("")
    if obj.reviews:
        lines.append("Review points:")
        lines.append("")
        for review in obj.reviews:
            flag = "blocking" if review.blocking else "check"
            lines.append(f"- line {review.line}, {review.rule} ({flag}): {review.reason}")
        lines.append("")
    rewrites = obj.all_rewrites
    if rewrites:
        parts = [f"{rule} x{count}" for rule, count in sorted(rewrites.items())]
        lines += ["Rewrites: " + ", ".join(parts) + ".", ""]
    return lines


def report_dict(result: ConversionResult) -> dict[str, Any]:
    """The report as plain data."""
    reviews = result.reviews
    counts = _unit_counts(result)
    return {
        "o2pg_version": __version__,
        "summary": {
            "objects": len(result.objects),
            "units_converted": counts[STATUS_CONVERTED],
            "units_review": counts[STATUS_REVIEW],
            "units_blocked": counts[STATUS_BLOCKED],
            "units_not_converted": counts[STATUS_NOT_CONVERTED],
            "rewrites_applied": sum(result.rewrites.values()),
            "review_points": len(reviews),
            "blocking_review_points": sum(1 for r in reviews if r.blocking),
            "statements": result.statements,
            "clean_statements": result.clean_statements,
            "mechanical_coverage_pct": round(result.coverage, 1),
        },
        "rewrites": dict(sorted(result.rewrites.items())),
        "objects": [
            {
                "object": obj.qualified,
                "source_types": list(obj.source_types),
                "file": obj.filename,
                "status": obj.status,
                "statements": obj.statements,
                "clean_statements": obj.clean_statements,
                "rewrites": dict(sorted(obj.all_rewrites.items())),
                "units": [
                    {
                        "name": unit.name,
                        "kind": unit.kind,
                        "status": unit.status,
                        "statements": unit.statements,
                        "clean_statements": unit.clean_statements,
                        "rewrites": dict(sorted(unit.rewrites.items())),
                    }
                    for unit in obj.units
                ],
                "review_points": [
                    {
                        "line": r.line,
                        "rule": r.rule,
                        "blocking": r.blocking,
                        "reason": r.reason,
                    }
                    for r in obj.reviews
                ],
            }
            for obj in result.objects
        ],
    }


def report_json(result: ConversionResult) -> str:
    """The report as JSON."""
    return json.dumps(report_dict(result), indent=2) + "\n"


def conversion_rules_markdown(rules: list[ConversionRule] | None = None) -> str:
    """Markdown reference for every conversion rule (``docs/conversion-rules.md``)."""
    selected = conversion_rules() if rules is None else rules
    rewrites = [r for r in selected if r.is_rewrite]
    reviews = [r for r in selected if not r.is_rewrite]
    lines = [
        "# o2pg conversion rule reference",
        "",
        "<!-- Generated by scripts/gen_rules_doc.py from the conversion registry. Do not edit "
        "by hand. -->",
        "",
        f"`o2pg convert` applies {len(rewrites)} mechanical rewrites and knows "
        f"{len(reviews)} kinds of review point. Every rewrite it makes is counted in the "
        "conversion report. Every review point is left in the output as "
        "`/* O2PG-REVIEW <rule>: <reason> */` on the line above the code. Blocking review "
        "points mark Oracle code that will not work as written; it is left in place on "
        "purpose, so the routine fails to compile instead of running with the wrong "
        "behaviour.",
        "",
        "## Rewrites",
        "",
    ]
    for rule in rewrites:
        lines += [f"### {rule.id}: {rule.title}", "", rule.description, ""]
        if rule.note:
            lines += [f"**Check:** {rule.note}", ""]
        if rule.see:
            lines += ["Related assessment rules: " + ", ".join(rule.see) + ".", ""]
    lines += ["## Review points", ""]
    for rule in reviews:
        kind = "blocking" if rule.blocking else "non-blocking"
        lines += [f"### {rule.id}: {rule.title}", "", f"*{kind}*", "", rule.description + ".", ""]
        if rule.see:
            lines += ["Related assessment rules: " + ", ".join(rule.see) + ".", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


__all__ = ["conversion_rules_markdown", "report_dict", "report_json", "report_markdown"]
