"""Suggested DDL from ``o2pg map-types``."""

from __future__ import annotations

import pytest

from helpers import column, constraint, inventory, partitioned, section, table
from o2pg.ddl import ident, suggest_ddl, translate_default, unquote_identifiers


@pytest.mark.parametrize(
    ("name", "expected"),
    [
        ("EMPLOYEES", "employees"),
        ("LIMIT", '"limit"'),
        ("Notes", "notes"),
        ("ORDER#", '"order#"'),
        ("A$B", "a$b"),
        ("MY COL", '"my col"'),
    ],
)
def test_ident(name: str, expected: str) -> None:
    assert ident(name) == expected


@pytest.mark.parametrize(
    ("expression", "sql"),
    [
        ("SYSDATE", "LOCALTIMESTAMP(0)"),
        ("sysdate ", "LOCALTIMESTAMP(0)"),
        ("SYSTIMESTAMP", "CURRENT_TIMESTAMP"),
        ("SYS_GUID()", "gen_random_uuid()"),
        ("USER", "CURRENT_USER"),
        ("42", "42"),
        ("-1.5", "-1.5"),
        ("'Y'", "'Y'"),
        ('"HR"."EMP_SEQ"."NEXTVAL"', "nextval('hr.emp_seq')"),
        ("emp_seq.nextval", "nextval('emp_seq')"),
        ("NULL", None),
        ("", None),
        ("TRUNC(SYSDATE) + 1", None),
    ],
)
def test_translate_default(expression: str, sql: str | None) -> None:
    assert translate_default(expression)[0] == sql


def test_untranslatable_default_leaves_todo() -> None:
    assert translate_default("TRUNC(SYSDATE)")[1] == "TODO default: TRUNC(SYSDATE)"


def test_unquote_identifiers() -> None:
    assert unquote_identifiers('"FIRST_NAME"||\' \'||"LIMIT"') == "first_name||' '||\"limit\""


