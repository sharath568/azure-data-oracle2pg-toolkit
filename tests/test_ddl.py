def test_ddl_schema_and_sequence(ddl: str) -> None:
    assert "CREATE SCHEMA IF NOT EXISTS app;" in ddl
    assert "CREATE SEQUENCE app.s1 INCREMENT BY 5 START WITH 100 CYCLE;" in ddl


def test_ddl_columns(ddl: str) -> None:
    assert "    id bigint NOT NULL," in ddl
    assert "order_date timestamp(0) DEFAULT LOCALTIMESTAMP(0) NOT NULL" in ddl
    assert "addr jsonb,  -- TODO user-defined type ADDR_T" in ddl
    assert "payload text,  -- TODO no mapping for ANYDATA" in ddl
    assert "total numeric GENERATED ALWAYS AS (id*2) STORED" in ddl
    assert "seq_id numeric GENERATED BY DEFAULT AS IDENTITY" in ddl
    assert "ts timestamp(6),  -- fractional seconds above 6 digits are truncated" in ddl


def test_ddl_keys_checks_and_partitioning(ddl: str) -> None:
    assert "CONSTRAINT orders_pk PRIMARY KEY (id)" in ddl
    assert ") PARTITION BY RANGE (order_date);" in ddl
    assert "-- TODO ORDERS_PK must include the partition key (ORDER_DATE)" in ddl
    assert "-- TODO check constraint ORDERS_CHK: CHECK (id > 0)" in ddl
    assert "SYS_C1" not in ddl
    assert "-- TODO REFERENCE partitioning has no PostgreSQL equivalent" in ddl


def test_ddl_foreign_keys(ddl: str) -> None:
    assert (
        "ALTER TABLE app.items ADD CONSTRAINT items_fk FOREIGN KEY (order_id) "
        "REFERENCES app.orders (id) ON DELETE CASCADE;"
    ) in ddl
    assert "-- TODO ITEMS_FK2: referenced constraint MISSING not in inventory" in ddl


def test_ddl_temporary_table_is_commented_out(ddl: str) -> None:
    assert "-- CREATE TEMP TABLE stage (" in ddl
    assert "\nCREATE TABLE app.stage" not in ddl
    assert "--     x varchar(10)" in ddl


def test_ddl_last_column_has_no_trailing_comma() -> None:
    ddl = suggest_ddl(inventory(table(), column("DATE", name="A"), column("DATE", name="B")))
    assert "    a timestamp(0),\n    b timestamp(0)\n);" in ddl
